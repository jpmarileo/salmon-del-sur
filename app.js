function applyLang(lang) {
  const t = translations[lang] || translations["es-CL"];
  document.documentElement.lang = lang === "en" ? "en" : lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (t[key]) el.textContent = t[key];
  });
  document.querySelector("[data-price='fresh']").textContent = t.prices.fresh;
  document.querySelector("[data-price='smoked']").textContent = t.prices.smoked;
  document.querySelector("[data-price='pack']").textContent = t.prices.pack;
  document.getElementById("whatsappBtn").href = t.wa;
  document.getElementById("whatsappBtn2").href = t.wa;
  document.title = lang === "en"
    ? "Southern Salmon | Fresh and smoked"
    : "Salmón del Sur | Fresco y ahumado";
  localStorage.setItem("lang", lang);
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("bg-salmon", btn.dataset.lang === lang);
    btn.classList.toggle("bg-white/15", btn.dataset.lang !== lang);
  });
  const url = new URL(window.location);
  url.searchParams.set("lang", lang);
  history.replaceState({}, "", url);
}

const startLang = new URLSearchParams(location.search).get("lang") || localStorage.getItem("lang") || "es-CL";
document.querySelectorAll(".lang-btn").forEach((btn) => {
  btn.addEventListener("click", () => applyLang(btn.dataset.lang));
});
applyLang(startLang);
